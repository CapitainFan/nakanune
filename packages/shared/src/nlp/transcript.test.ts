import { describe, expect, it } from 'vitest';
import { parseTelegramTranscript } from './transcript';

// Формат — как копирует Telegram Desktop на macOS: перед «г.» узкий неразрывный пробел
// U+202F. Имена вымышленные.
const TRANSCRIPT = `Аня Смирнова, [28 сент. 2026\u202fг., 14:48:15]:
Что по проге на завтра


Миша Орлов, [28 сент. 2026 г., 14:48:58]:
5 заданий тех из классной работы, на 29.09-06.10 до 6 октября


вроде еще какое-то есть там срок до 29сент посмотри короче


Аня Смирнова, [23 сент. 2026 г., 14:01:11 (23 сент. 2026 г., 14:01:13)]:
А че по геоме`;

describe('parseTelegramTranscript', () => {
  it('делит переписку на сообщения со временем по Минску', () => {
    const messages = parseTelegramTranscript(TRANSCRIPT);
    expect(messages).toEqual([
      {
        author: 'Аня Смирнова',
        sentAt: new Date('2026-09-28T11:48:15Z'),
        text: 'Что по проге на завтра',
      },
      {
        author: 'Миша Орлов',
        sentAt: new Date('2026-09-28T11:48:58Z'),
        // Сообщения одного автора подряд — под одним заголовком, одним блоком
        text: '5 заданий тех из классной работы, на 29.09-06.10 до 6 октября\n\nвроде еще какое-то есть там срок до 29сент посмотри короче',
      },
      {
        author: 'Аня Смирнова',
        // У отредактированного берём время отправки, а не правки
        sentAt: new Date('2026-09-23T11:01:11Z'),
        text: 'А че по геоме',
      },
    ]);
  });

  it('обычный текст — не переписка', () => {
    expect(parseTelegramTranscript('Матан: к пятнице №1234')).toBeNull();
  });
});
